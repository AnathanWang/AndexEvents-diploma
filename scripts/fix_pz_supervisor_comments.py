def paragraph_text(p: ET.Element) -> str:
    return "".join((t.text or "") for t in p.iter(f"{{{NS}}}t"))


def normalize_spaces(text: str) -> str:
    return re.sub(r"\s+", " ", text.replace("\u2002", " ")).strip()


